// Jalankan di: ROOT/packages/sdk  ->  node scripts/export-abis.mjs
// Copies ABIs from the Foundry build output into typed `as const` modules.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const dest = join(here, "../src/abis");
mkdirSync(dest, { recursive: true });

// [exportName, artifact file, contract name]
const contracts = [
  ["asterraHubAbi", "AsterraHub.sol", "AsterraHub"],
  ["asterraHookAbi", "AsterraHook.sol", "AsterraHook"],
  ["asterraRouterAbi", "AsterraRouter.sol", "AsterraRouter"],
  ["asterraPositionsAbi", "AsterraPositions.sol", "AsterraPositions"],
  ["dlmmPoolAbi", "AsterraDLMMPool.sol", "AsterraDLMMPool"],
  ["dlmmFactoryAbi", "AsterraDLMMFactory.sol", "AsterraDLMMFactory"],
  ["dlmmLimitOrdersAbi", "AsterraDLMMLimitOrders.sol", "AsterraDLMMLimitOrders"],
  ["dammPoolAbi", "AsterraDAMMPool.sol", "AsterraDAMMPool"],
  ["dammFactoryAbi", "AsterraDAMMFactory.sol", "AsterraDAMMFactory"],
  ["launchpadAbi", "AsterraLaunchpad.sol", "AsterraLaunchpad"],
  ["launchTokenAbi", "AsterraLaunchToken.sol", "AsterraLaunchToken"],
  ["asterTokenAbi", "AsterraToken.sol", "AsterraToken"],
  ["lendingVaultAbi", "AsterraLendingVault.sol", "AsterraLendingVault"],
  ["creditManagerAbi", "AsterraCreditManager.sol", "AsterraCreditManager"],
  ["buybackAbi", "AsterraBuyback.sol", "AsterraBuyback"],
  ["faucetTokenAbi", "FaucetToken.sol", "FaucetToken"],
  ["mockPriceFeedAbi", "MockPriceFeed.sol", "MockPriceFeed"],
  ["poolManagerAbi", "IPoolManager.sol", "IPoolManager"],
];

const exported = [];
for (const [name, file, contract] of contracts) {
  const p = join(out, file, `${contract}.json`);
  if (!existsSync(p)) {
    // not in this build output: keep the committed module and its export instead of dropping it from the index
    if (existsSync(join(dest, `${name}.ts`))) exported.push(name);
    else console.warn(`skip ${contract} (not built)`);
    continue;
  }
  const { abi } = JSON.parse(readFileSync(p, "utf8"));
  writeFileSync(join(dest, `${name}.ts`), `// Generated by scripts/export-abis.mjs. Do not edit.\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`);
  exported.push(name);
}
writeFileSync(
  join(dest, "index.ts"),
  `// Generated by scripts/export-abis.mjs. Do not edit.\n${exported.map((n) => `export { ${n} } from "./${n}.js";`).join("\n")}\n`,
);
console.log(`exported ${exported.length} ABIs`);
